// Every cosmetic item definition present in the 12.50 paks (generated by Tools/cosmetics.py).
const COSMETICS_FILE = path.join(__dirname, "..", "data", "cosmetics.json");

function cosmeticItem(templateId) {
  return { templateId, attributes: { max_level_bonus: 0, level: 1, item_seen: true, xp: 0, variants: [], favorite: false }, quantity: 1 };
}

class Mcp {
  constructor(cfg, log) {
    this.cfg = cfg;
    this.log = log;
    this.tpl = templates(cfg.accountId, cfg);
    this.cosmetics = fs.existsSync(COSMETICS_FILE) ? JSON.parse(fs.readFileSync(COSMETICS_FILE, "utf8")).items.map((i) => i.templateId) : [];
    fs.mkdirSync(DIR, { recursive: true });
    log(`[MCP] ${this.cosmetics.length} local cosmetics available for the locker`);
  }

  load(profileId) {
    const file = path.join(DIR, `${profileId}.json`);
    let p;
    if (fs.existsSync(file)) p = JSON.parse(fs.readFileSync(file, "utf8"));
    else {
      const make = this.tpl[profileId] || (() => templates(this.cfg.accountId, this.cfg).metadata());
      p = make();
      p.profileId = profileId;
    }
    if (profileId === "athena" && this.ensureCosmetics(p)) this.save(p);
    else if (!fs.existsSync(file)) this.save(p);
    return p;
  }

  // Grants every local cosmetic (item id = templateId, so equips can reference either).
  ensureCosmetics(p) {
    let added = 0;
    for (const t of this.cosmetics) {
      if (!p.items[t]) {
        p.items[t] = cosmeticItem(t);
        added++;
      }
    }
    if (added) this.log(`[MCP] granted ${added} cosmetics to athena profile`);
    return added > 0;
  }

  save(p) {
    fs.writeFileSync(path.join(DIR, `${p.profileId}.json`), JSON.stringify(p, null, 2));
  }

  // Returns the MCP response body for /fortnite/api/game/v2/profile/:id/client/:command
  handle(command, profileId, body, rvn) {
    const p = this.load(profileId);
    const changes = [];
    const handler = COMMANDS[command];
    if (handler) handler(p, body || {}, changes);
    else this.log(`[MCP] unhandled command ${command} (profile ${profileId}); returning profile unchanged`);

    if (changes.length) {
      p.rvn += 1;
      p.commandRevision += 1;
      p.updated = now();
      this.save(p);
    }
    // Always answer with a full profile: simplest correct behaviour for a single local client.
    return {
      profileRevision: p.rvn,
      profileId,
      profileChangesBaseRevision: p.rvn - (changes.length ? 1 : 0),
      profileChanges: [{ changeType: "fullProfileUpdate", profile: p }],
      profileCommandRevision: p.commandRevision,
      serverTime: now(),
      responseVersion: 1,
    };
  }
}

function statChange(p, name, value, changes) {
  p.stats.attributes[name] = value;
  changes.push({ changeType: "statModified", name, value });
}

const COMMANDS = {
  QueryProfile() {},
  ClientQuestLogin() {},
  SetMtxPlatform(p, b, c) {
    statChange(p, "current_mtx_platform", b.newPlatform || "EpicPC", c);
  },
  SetLastUsedBattleLabFile(p, b, c) {
    statChange(p, "last_used_battlelab_file", b.fileName || b.battleLabFile || "", c);
  },

  // ---- Locker (12.x CosmeticLocker items)
  SetCosmeticLockerSlot(p, b, c) {
    const locker = p.items[b.lockerItem] || p.items.sandbox_loadout;
    if (!locker) return;
    const slots = (locker.attributes.locker_slots_data ||= { slots: {} }).slots;
    const cat = b.category;
    const size = cat === "Dance" ? 6 : cat === "ItemWrap" ? 7 : 1;
    const slot = (slots[cat] ||= { items: new Array(size).fill(""), activeVariants: new Array(size).fill(null) });
    while (slot.items.length < size) slot.items.push("");
    const item = b.itemToSlot ? resolveTemplate(p, b.itemToSlot) : "";
    if (cat === "ItemWrap" && b.slotIndex === -1) slot.items = slot.items.map(() => item);
    else slot.items[Math.max(0, b.slotIndex || 0)] = item;
    if (Array.isArray(b.variantUpdates) && b.variantUpdates.length) {
      const idx = Math.max(0, b.slotIndex || 0);
      slot.activeVariants ||= new Array(size).fill(null);
      slot.activeVariants[idx] = { variants: b.variantUpdates.map((v) => ({ channel: v.channel, active: v.active })) };
      const owned = p.items[b.itemToSlot];
      if (owned) {
        for (const v of b.variantUpdates) {
          const cur = owned.attributes.variants.find((x) => x.channel === v.channel);
          if (cur) cur.active = v.active;
          else owned.attributes.variants.push({ channel: v.channel, active: v.active, owned: v.owned || [v.active] });
        }
      }
    }
    c.push({ changeType: "itemAttrChanged", itemId: b.lockerItem, attributeName: "locker_slots_data", attributeValue: locker.attributes.locker_slots_data });
    // Mirror into favorite_* stats (read by older UI paths and by the game server for the player's loadout).
    const favName = { Character: "favorite_character", Backpack: "favorite_backpack", Pickaxe: "favorite_pickaxe", Glider: "favorite_glider", SkyDiveContrail: "favorite_skydivecontrail", MusicPack: "favorite_musicpack", LoadingScreen: "favorite_loadingscreen" }[cat];
    if (favName) statChange(p, favName, item, c);
    if (cat === "Dance") statChange(p, "favorite_dance", slot.items, c);
    if (cat === "ItemWrap") statChange(p, "favorite_itemwraps", slot.items, c);
  },
  SetCosmeticLockerBanner(p, b, c) {
    const locker = p.items[b.lockerItem] || p.items.sandbox_loadout;
    if (!locker) return;
    locker.attributes.banner_icon_template = b.bannerIconTemplateName || "";
    locker.attributes.banner_color_template = b.bannerColorTemplateName || "";
    statChange(p, "banner_icon", locker.attributes.banner_icon_template, c);
    statChange(p, "banner_color", locker.attributes.banner_color_template, c);
  },
  SetCosmeticLockerName(p, b, c) {
    const locker = p.items[b.lockerItem] || p.items.sandbox_loadout;
    if (locker) locker.attributes.locker_name = b.name || "";
    c.push({ changeType: "itemAttrChanged", itemId: b.lockerItem, attributeName: "locker_name", attributeValue: b.name || "" });
  },
  EquipBattleRoyaleCustomization(p, b, c) {
    const map = { Character: "favorite_character", Backpack: "favorite_backpack", Pickaxe: "favorite_pickaxe", Glider: "favorite_glider", SkyDiveContrail: "favorite_skydivecontrail", MusicPack: "favorite_musicpack", LoadingScreen: "favorite_loadingscreen" };
    const item = b.itemToSlot ? resolveTemplate(p, b.itemToSlot) : "";
    if (map[b.slotName]) statChange(p, map[b.slotName], item, c);
    else if (b.slotName === "Dance" || b.slotName === "ItemWrap") {
      const name = b.slotName === "Dance" ? "favorite_dance" : "favorite_itemwraps";
      const arr = [...(p.stats.attributes[name] || [])];
      if (b.slotName === "ItemWrap" && b.indexWithinSlot === -1) arr.fill(item);
      else arr[b.indexWithinSlot || 0] = item;
      statChange(p, name, arr, c);
    }
  },
  MarkItemSeen(p, b, c) {
    for (const id of b.itemIds || []) {
      if (!p.items[id]) continue;
      p.items[id].attributes.item_seen = true;
      c.push({ changeType: "itemAttrChanged", itemId: id, attributeName: "item_seen", attributeValue: true });
    }
  },
  SetItemFavoriteStatusBatch(p, b, c) {
    (b.itemIds || []).forEach((id, i) => {
      if (!p.items[id]) return;
      const fav = Array.isArray(b.itemFavStatus) ? !!b.itemFavStatus[i] : !!b.bFavorite;
      p.items[id].attributes.favorite = fav;
      c.push({ changeType: "itemAttrChanged", itemId: id, attributeName: "favorite", attributeValue: fav });
    });
  },
  SetItemFavoriteStatus(p, b, c) {
    if (!p.items[b.targetItemId]) return;
    p.items[b.targetItemId].attributes.favorite = !!b.bFavorite;
    c.push({ changeType: "itemAttrChanged", itemId: b.targetItemId, attributeName: "favorite", attributeValue: !!b.bFavorite });
  },
  SetBattleRoyaleBanner(p, b, c) {
    statChange(p, "banner_icon", b.homebaseBannerIconId || "", c);
    statChange(p, "banner_color", b.homebaseBannerColorId || "", c);
  },
};

// Item ids equal template ids for granted cosmetics; accept either form.
function resolveTemplate(p, id) {
  return p.items[id] ? p.items[id].templateId : id;
}

module.exports = { Mcp };
